#!/bin/bash
# Fixture test for scripts/check-mock-ban.sh and the depguard mock-ban rule.

set -euo pipefail

REPO_ROOT="${1:-.}"
REPO_ROOT="$(cd "$REPO_ROOT" && pwd)"
SCRIPT="$REPO_ROOT/scripts/check-mock-ban.sh"
GOLANGCI="$REPO_ROOT/.golangci.yml"

FAILURES=0
WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT

make_fixture() {
    local destination="$1"
    mkdir -p "$destination"
    tar -C "$REPO_ROOT" -cf - go.mod scripts/check-mock-ban.sh | tar -x -C "$destination"
    mkdir -p "$destination/internal/example"
    printf 'package example\n\nfunc Hello() {}\n' > "$destination/internal/example/example.go"
    chmod +x "$destination/scripts/check-mock-ban.sh"
}

FIXTURE="$WORKDIR/fixture"
make_fixture "$FIXTURE"
CHECK="$FIXTURE/scripts/check-mock-ban.sh"

echo "Test 1: check-mock-ban passes on a clean fixture..."
CLEAN_OUT=$(mktemp)
if "$CHECK" "$FIXTURE" > "$CLEAN_OUT" 2>&1; then
    echo "  PASS"
else
    echo "  FAIL: expected exit 0 on clean tree, got non-zero"
    cat "$CLEAN_OUT"
    FAILURES=$((FAILURES + 1))
fi
rm -f "$CLEAN_OUT"

echo "Test 2: mockery-generated header is rejected..."
printf '// Code generated by mockery v2.53.1. DO NOT EDIT.\npackage example\n' \
    > "$FIXTURE/internal/example/mock_hello.go"
set +e
OUTPUT=$("$CHECK" "$FIXTURE" 2>&1)
STATUS=$?
set -e
if [[ $STATUS -eq 0 ]]; then
    echo "  FAIL: expected non-zero exit for mockery output"
    echo "$OUTPUT"
    FAILURES=$((FAILURES + 1))
elif ! grep -q "mockery-generated" <<< "$OUTPUT"; then
    echo "  FAIL: expected mockery-generated failure message"
    echo "$OUTPUT"
    FAILURES=$((FAILURES + 1))
else
    echo "  PASS"
fi
rm -f "$FIXTURE/internal/example/mock_hello.go"

echo "Test 3: banned mock module in go.mod is rejected..."
printf '\nrequire github.com/golang/mock v1.6.0\n' >> "$FIXTURE/go.mod"
set +e
OUTPUT=$("$CHECK" "$FIXTURE" 2>&1)
STATUS=$?
set -e
if [[ $STATUS -eq 0 ]]; then
    echo "  FAIL: expected non-zero exit for golang/mock in go.mod"
    echo "$OUTPUT"
    FAILURES=$((FAILURES + 1))
elif ! grep -q "github.com/golang/mock" <<< "$OUTPUT"; then
    echo "  FAIL: expected the banned module to be named"
    echo "$OUTPUT"
    FAILURES=$((FAILURES + 1))
else
    echo "  PASS"
fi
cp "$REPO_ROOT/go.mod" "$FIXTURE/go.mod"

echo "Test 4: testify itself is not a banned module..."
if ! grep -q 'github.com/stretchr/testify' "$FIXTURE/go.mod"; then
    echo "  FAIL: fixture go.mod is missing testify (assert/require must stay allowed)"
    FAILURES=$((FAILURES + 1))
else
    set +e
    OUTPUT=$("$CHECK" "$FIXTURE" 2>&1)
    STATUS=$?
    set -e
    if [[ $STATUS -ne 0 ]]; then
        echo "  FAIL: testify in go.mod must not fail the mock-module check"
        echo "$OUTPUT"
        FAILURES=$((FAILURES + 1))
    else
        echo "  PASS"
    fi
fi

echo "Test 5: .golangci.yml mock-ban rule denies known mock libraries..."
if [[ ! -f "$GOLANGCI" ]]; then
    echo "  FAIL: $GOLANGCI missing"
    FAILURES=$((FAILURES + 1))
else
    missing=0
    for pkg in \
        github.com/stretchr/testify/mock \
        github.com/golang/mock \
        go.uber.org/mock \
        github.com/vektra/mockery
    do
        if ! grep -q "$pkg" "$GOLANGCI"; then
            echo "  FAIL: $GOLANGCI mock-ban does not deny $pkg"
            missing=1
            FAILURES=$((FAILURES + 1))
        fi
    done
    if ! grep -q 'mock-ban:' "$GOLANGCI"; then
        echo "  FAIL: $GOLANGCI has no mock-ban depguard rule"
        missing=1
        FAILURES=$((FAILURES + 1))
    fi
    if [[ $missing -eq 0 ]]; then
        echo "  PASS"
    fi
fi

echo "Test 6: check-mock-ban.sh is committed executable..."
mode=$(git -C "$REPO_ROOT" ls-files -s -- "scripts/check-mock-ban.sh" | awk '{print $1}')
if [[ "$mode" == "100755" ]]; then
    echo "  PASS: git mode is 100755"
else
    echo "  FAIL: git mode is '${mode:-missing}', expected 100755"
    FAILURES=$((FAILURES + 1))
fi
if [[ -x "$SCRIPT" ]]; then
    echo "  PASS: executable on disk"
else
    echo "  FAIL: not executable on disk"
    FAILURES=$((FAILURES + 1))
fi

echo ""
if [[ $FAILURES -eq 0 ]]; then
    echo "All mock-ban tests passed"
    exit 0
else
    echo "FAIL: $FAILURES mock-ban test(s) failed"
    exit 1
fi
