#!/bin/bash
# Mock-framework ban (quality-controls C1 / guardrail R1).
# depguard covers imports. This script covers mockery headers and go.mod modules.
# Usage: scripts/check-mock-ban.sh [repo-root]

set -euo pipefail

REPO_ROOT="${1:-.}"
cd "$REPO_ROOT"

if ! command -v rg >/dev/null 2>&1; then
    echo "FAIL: rg is required for check-mock-ban" >&2
    exit 1
fi

ERRORS=0

if [[ ! -f go.mod ]]; then
    echo "FAIL: go.mod not found in $REPO_ROOT" >&2
    exit 1
fi

BANNED_MODULES=(
    github.com/golang/mock
    go.uber.org/mock
    github.com/vektra/mockery
    github.com/petergtz/pegomock
    github.com/maxbrunsfeld/counterfeiter
    github.com/matryer/moq
    github.com/derision-test/go-mockgen
    github.com/DATA-DOG/go-sqlmock
    github.com/agiledragon/gomonkey
    github.com/prashantv/gostub
    github.com/undefinedlabs/go-mpatch
    github.com/bouk/monkey
    github.com/bytedance/mockey
    github.com/gojuno/minimock
)

mod_paths=$(awk '
    /^require \(/ { inreq=1; next }
    inreq && /^\)/ { inreq=0; next }
    inreq {
        gsub(/\/\/.*/, "")
        if ($1 == "") next
        print $1
        next
    }
    /^require[ \t]+[^(\t ]/ {
        gsub(/\/\/.*/, "")
        print $2
    }
' go.mod)

while IFS= read -r mod; do
    [[ -z "$mod" ]] && continue
    for banned in "${BANNED_MODULES[@]}"; do
        if [[ "$mod" == "$banned" || "$mod" == "$banned"/* ]]; then
            echo "FAIL: mock module '$mod' is listed in go.mod (banned prefix $banned)" >&2
            echo "Prefer a hand-written fake per port; mock frameworks are banned (R1)." >&2
            ERRORS=$((ERRORS + 1))
        fi
    done
done <<< "$mod_paths"

hits=$(rg -n --glob '*.go' --glob '!**/testdata/**' \
    -e 'Code generated by mockery' \
    -e 'Code generated by Mockery' \
    . || true)
if [[ -n "$hits" ]]; then
    echo "FAIL: mockery-generated files are banned (R1); use a hand-written fake:" >&2
    echo "$hits" >&2
    ERRORS=$((ERRORS + 1))
fi

if [[ "$ERRORS" -ne 0 ]]; then
    exit 1
fi

echo "OK: no mock modules in go.mod and no mockery-generated files"
